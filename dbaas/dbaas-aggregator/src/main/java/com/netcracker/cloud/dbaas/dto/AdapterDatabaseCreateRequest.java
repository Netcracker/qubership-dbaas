package com.netcracker.cloud.dbaas.dto;

import com.fasterxml.jackson.annotation.JsonInclude;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Data;

import java.util.List;
import java.util.Map;

@Data
@Schema(description = "The request to create database for REST dbaas adapter")
public class AdapterDatabaseCreateRequest {
    @Schema(description = "Metadata is a json object with any information about database, adapter should save it inside database")
    private Map<String, Object> metadata;
    @Schema(description = "Database name should be started from name prefix. If not specified, should use default dbaas_")
    private String namePrefix;
    @JsonInclude(JsonInclude.Include.NON_NULL)
    @Schema(description = "Additional settings for creating database")
    private Map<String, Object> settings;
    @Deprecated
    @Schema(deprecated = true, description = "The list of identifiers of initial scripts which should be executed in the adapter. " +
            "Deprecated in v1 and v2, will be removed in v3.")
    private List<String> initScriptIdentifiers;
    @Schema(description = "Password for user. Will be generated by adapter if not specified")
    private String password;
    @Schema(description = "Username user to create to connect to database. Will be generated by adapter if not specified")
    private String username;
    @Schema(description = "Database name to create. Will be generated by adapter with namePrefix if dbName not specified")
    private String dbName;

    public static final String EXAMPLE_REQUEST = """
            {
              "metadata": {
                "classifier": { "scope": "service", "namespace": "payments" },
                "microserviceName": "postgres-database-service"
              },
              "dbName": "postgres-database",
              "settings": { "pgExtension": ["extension"] }
            }
            """;
}
